// Copies contract ABIs (from forge's out/) and deployed addresses (contracts/deployments/*.json)
// into src/lib/generated/, so the website never hand-maintains either.
//   node scripts/sync-contracts.mjs
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(new URL('..', import.meta.url).pathname)
const out = path.join(root, 'contracts/out')
const depDir = path.join(root, 'contracts/deployments')
const gen = path.join(root, 'src/lib/generated')
fs.mkdirSync(gen, { recursive: true })

const abi = (file, name) => JSON.parse(fs.readFileSync(path.join(out, file, `${name}.json`), 'utf8')).abi

const abis = {
  CallMarket: abi('CallMarket.sol', 'CallMarket'),
  PutMarket: abi('PutMarket.sol', 'PutMarket'),
  OptionNFT: abi('OptionNFT.sol', 'OptionNFT'),
  AssetRegistry: abi('AssetRegistry.sol', 'AssetRegistry'),
  FeeVault: abi('FeeVault.sol', 'FeeVault'),
  StakingPool: abi('StakingPool.sol', 'StakingPool'),
  BuybackBurner: abi('BuybackBurner.sol', 'BuybackBurner'),
  Router: abi('Router.sol', 'Router'),
  UsdgRewards: abi('UsdgRewards.sol', 'UsdgRewards'),
  // Mock ERC20/WETH ABIs are a superset of the real ones (they add `mint`, used by the devnet faucet).
  ERC20: abi('Mocks.sol', 'MockERC20'),
  WETH: abi('Mocks.sol', 'MockWETH'),
}

const header = '// Generated by scripts/sync-contracts.mjs. Do not edit.\n'
fs.writeFileSync(
  path.join(gen, 'abis.ts'),
  header + `export const ABIS = ${JSON.stringify(abis, null, 2)} as const\n`,
)

const deployments = {}
if (fs.existsSync(depDir)) {
  for (const f of fs.readdirSync(depDir)) {
    if (!f.endsWith('.json')) continue
    const id = f.replace('.json', '')
    if (!/^\d+$/.test(id)) continue // only <chainId>.json (skip safes-*, *.dry-run)
    const d = JSON.parse(fs.readFileSync(path.join(depDir, f), 'utf8'))
    // First block the protocol exists at: chain reads start here (public RPCs cap log ranges, e.g. 10M blocks).
    const run = path.join(root, 'contracts/broadcast/Deploy.s.sol', id, 'run-latest.json')
    if (fs.existsSync(run)) {
      const blocks = JSON.parse(fs.readFileSync(run, 'utf8')).receipts.map((r) => parseInt(r.blockNumber, 16)).filter(Number.isFinite)
      if (blocks.length) d.deployBlock = Math.min(...blocks)
    }
    deployments[id] = d
  }
}
fs.writeFileSync(path.join(gen, 'deployments.json'), JSON.stringify(deployments, null, 2) + '\n')
console.log(`abis: ${Object.keys(abis).length}, deployments: ${Object.keys(deployments).join(', ') || 'none'}`)
